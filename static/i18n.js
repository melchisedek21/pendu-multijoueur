// Les messages d'erreur de l'API sont en francais : on les relie a une cle traduisible
const ERREURS_API = {
  "L'identifiant doit contenir entre 3 et 20 caracteres : lettres, chiffres ou underscore uniquement.": "erreurs.id_format",
  "Le mot de passe doit contenir au moins 6 caracteres.": "erreurs.mdp_court",
  "Le mot de passe ne doit pas depasser 72 caracteres.": "erreurs.mdp_long",
  "Cet identifiant est deja pris.": "erreurs.id_pris",
  "Identifiant ou mot de passe incorrect.": "erreurs.identifiants_incorrects",
  "Jeton invalide ou expire.": "erreurs.jeton_invalide",
  "Le mot de passe actuel est incorrect.": "erreurs.ancien_mdp",
};

function detecterLangue() {
  const sauvegardee = localStorage.getItem("pendu_langue");
  if (sauvegardee && TRADUCTIONS[sauvegardee]) return sauvegardee;
  const navigateur = (navigator.language || "fr").slice(0, 2).toLowerCase();
  return TRADUCTIONS[navigateur] ? navigateur : "fr";
}

let langueActuelle = detecterLangue();

function lireCle(dictionnaire, cle) {
  return cle.split(".").reduce((noeud, morceau) => (noeud == null ? undefined : noeud[morceau]), dictionnaire);
}

/** Retourne la traduction de `cle` (repli sur le francais), avec {params} remplaces. */
function t(cle, params = {}) {
  let valeur = lireCle(TRADUCTIONS[langueActuelle], cle);
  if (valeur === undefined) valeur = lireCle(TRADUCTIONS.fr, cle);
  if (valeur === undefined) return cle;
  if (typeof valeur !== "string") return valeur;
  return valeur.replace(/\{(\w+)\}/g, (tout, nom) => (nom in params ? params[nom] : tout));
}

/** Traduit un message d'erreur venant de l'API (texte francais) dans la langue choisie. */
function traduireErreurApi(detail) {
  return ERREURS_API[detail] ? t(ERREURS_API[detail]) : detail;
}

function appliquerTraductions(racine = document) {
  document.documentElement.lang = langueActuelle;
  document.title = t("app.titre");
  racine.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  racine.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  racine.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  racine.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute("aria-label", t(el.dataset.i18nTitle));
  });
}

function changerLangue(langue) {
  if (!TRADUCTIONS[langue]) return;
  langueActuelle = langue;
  localStorage.setItem("pendu_langue", langue);
  appliquerTraductions();
  document.dispatchEvent(new CustomEvent("langue-changee", { detail: langue }));
}
